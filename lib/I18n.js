// ── Función pura de detección ─────────────────
function detectLocale() {
  if (typeof window === 'undefined') return 'es'
  const lang = navigator.language?.toLowerCase() || 'es'
  if (lang.startsWith('fr')) return 'fr'
  if (lang.startsWith('en')) return 'en'
  return 'es'
}

// ── Hook de detección de idioma ────────────────
// Usa useState+useEffect para evitar mismatch SSR/cliente
export function useLocale() {
  // Importamos useState/useEffect dinámicamente para no romper el módulo
  const { useState, useEffect } = require('react')
  const [locale, setLocale] = useState('es') // SSR: español por defecto

  useEffect(() => {
    setLocale(detectLocale())
  }, [])

  return translations[locale]
}

export default translations